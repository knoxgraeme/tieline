await test("writes the file, keeps it when nothing changed, and --check reports whether it is current", () => {
  const ws = workspace();
  const first = captureIO();
  assert.equal(runScreensScenesCommand({ repository: ws.root }, first.io), 0);
  assert.match(first.output(), /^Created e2e\/pages\.generated\.screens\.ts: 2 generated page scene\(s\); 1 page\(s\) captured by another test, 1 marked not captured\.\n$/);
  const written = readFileSync(`${ws.root}/${GENERATED}`, "utf8");
  assert.equal(written, planFor(ws).plan.content);

  const again = captureIO();
  assert.equal(runScreensScenesCommand({ repository: ws.root, json: true }, again.io), 0);
  assert.equal((JSON.parse(again.output()) as { status: string }).status, "unchanged");

  const current = captureIO();
  assert.equal(runScreensScenesCommand({ repository: ws.root, check: true }, current.io), 0);
  assert.match(current.output(), /is current: 2 generated page scene\(s\)/);

  // An agent writes its own scene for the notes list: the generated one must go.
  ws.write("e2e/notes.screens.ts", 'test("list", { tag: "@screen:notes-list" }, async () => {});\n');
  const stale = captureIO();
  assert.equal(runScreensScenesCommand({ repository: ws.root, check: true }, stale.io), 1);
  assert.match(stale.output(), /out of date with the catalog; run `tieline screens scenes`/);
  assert.equal(readFileSync(`${ws.root}/${GENERATED}`, "utf8"), written, "--check writes nothing");
  assert.equal(runScreensScenesCommand({ repository: ws.root }, captureIO().io), 0);
  assert.doesNotMatch(readFileSync(`${ws.root}/${GENERATED}`, "utf8"), /@screen:notes-list/);
});

await test("refuses to write through a link out of the repository", () => {
  const ws = workspace({ file: "linked/pages.screens.ts" });
  symlinkSync(tmpdir(), `${ws.root}/linked`);
  assert.throws(() => runScreensScenesCommand({ repository: ws.root }, captureIO().io), /outside the repository; nothing was generated/);
});

await test("fails the strict audit while the generated file is missing or stale, and passes it once current", async () => {
  const ws = workspace();
  const settings = screenSettingsForRepository(ws.root)!;
  const { catalog } = loadScreenCatalog(ws.root, settings, new Set(["NOTES", "SHARING"]));
  const scan = scanScreenScenes(ws.root, settings.sceneTests);
  assert.deepEqual(generatedScenesStatus({ repositoryRoot: ws.root, settings, catalog, scan }), {
    status: "stale",
    file: GENERATED,
    detail: "the file does not exist",
  });
  const missing = captureIO();
  assert.equal(await runScreensAuditCommand({ repository: ws.root, strict: true }, missing.io), 1);
  assert.match(missing.output(), /scenes    e2e\/pages\.generated\.screens\.ts: the file does not exist; run `tieline screens scenes`/);
  assert.match(missing.output(), /the generated page scenes are out of date \(the file does not exist\); run `tieline screens scenes`/);

  runScreensScenesCommand({ repository: ws.root }, captureIO().io);
  const after = captureIO();
  await runScreensAuditCommand({ repository: ws.root, strict: true, json: true }, after.io);
  const audit = JSON.parse(after.output()) as { generated_scenes: { status: string }; strict: { failures: string[] } };
  assert.equal(audit.generated_scenes.status, "current");
  assert.ok(!audit.strict.failures.some((failure) => /generated page scenes/.test(failure)));
});

