const NOTES_YAML = `version: 1
capability: NOTES
screens:
  - key: notes-list
    title: Notes list
    route: /notes
    kind: page
    when: A member opens Notes.
  - key: note-detail
    title: "A note, opened"
    route: /notes/:noteId
    kind: page
    when: A member opens a note.
    applies_to:
      role: [member]
  - key: notes-settings
    title: Notes settings
    route: /notes/settings
    kind: page
    when: A member opens settings.
    not_captured:
      reason: flag-off
      detail: Settings are behind the settings flag.
  - key: notes-about
    title: About "Notes"
    route: /about
    kind: page
    when: Anyone opens About.
  - key: notes-list-empty
    title: Notes list, no notes yet
    route: /notes
    kind: state
    when: A member without notes opens Notes.
`;

function workspace(generated: unknown = { file: GENERATED, setup: "e2e/screens.setup.ts" }): ScreensWorkspace {
  const ws = createScreensWorkspace({
    git: true,
    screens: { enabled: true, capture: generated === null ? {} : { generated_scenes: generated } },
    catalog: {
      ".tieline/screens/NOTES.yaml": NOTES_YAML,
      // An agent-written scene already captures the About page.
      "e2e/about.screens.ts": 'test("about", { tag: "@screen:notes-about" }, async () => {});\n',
    },
  });
  workspaces.push(ws);
  return ws;
}

function planFor(ws: ScreensWorkspace) {
  const settings = screenSettingsForRepository(ws.root)!;
  const { catalog, issues } = loadScreenCatalog(ws.root, settings, new Set(["NOTES", "SHARING"]));
  assert.deepEqual(issues, []);
  const scan = scanScreenScenes(ws.root, settings.sceneTests);
  return { settings, catalog, scan, plan: planGeneratedScenes({ settings, catalog, scan }) };
}

