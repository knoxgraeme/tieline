function fakePage(status = 200) {
  const visited: string[] = [];
  return {
    visited,
    page: {
      async goto(url: string) {
        visited.push(url);
        return { ok: () => status < 400, status: () => status };
      },
    },
  };
}

const NOTE: GeneratedScreen = { key: "note-detail", title: "A note", route: "/notes/:noteId", applies_to: { role: ["member"] } };

await test("prepares the page, opens the URL it returns, and captures the screen", async () => {
  const { page, visited } = fakePage();
  const captured: string[] = [];
  const prepared: Array<{ key: string; role: readonly string[] | undefined }> = [];
  await openAndCapture(
    page,
    NOTE,
    async (_page, screen) => {
      prepared.push({ key: screen.key, role: screen.applies_to?.role });
      return "/notes/note-1";
    },
    async (_page, key) => {
      captured.push(key);
    }
  );
  assert.deepEqual(prepared, [{ key: "note-detail", role: ["member"] }]);
  assert.deepEqual(visited, ["/notes/note-1"]);
  assert.deepEqual(captured, ["note-detail"]);

  const plain = fakePage();
  await openAndCapture(plain.page, { ...NOTE, route: "/notes" }, undefined, async () => undefined);
  assert.deepEqual(plain.visited, ["/notes"], "without a setup module the catalogued route is opened");
});

await test("refuses a route left with parameters and a page that answers with an error", async () => {
  const unvisited = fakePage();
  await assert.rejects(
    openAndCapture(unvisited.page, NOTE, async () => undefined, async () => undefined),
    /route \/notes\/:noteId, which has parameters: return the URL to open from prepare\(\)/
  );
  assert.deepEqual(unvisited.visited, []);
  for (const route of ["/files/*", "/notes/[noteId]"]) {
    await assert.rejects(openAndCapture(fakePage().page, { ...NOTE, route }, undefined, async () => undefined), /has parameters/);
  }
  const captured: string[] = [];
  await assert.rejects(
    openAndCapture(fakePage(404).page, { ...NOTE, route: "/missing" }, undefined, async (_page, key) => {
      captured.push(key);
    }),
    /\/missing answered HTTP 404, so it was not captured/
  );
  assert.deepEqual(captured, [], "an error page is never captured as the screen");
});

