await test("reads the generated scenes block and refuses patterns", () => {
  assert.equal(readScreensConfig({ screens: { enabled: true } })?.capture.generated_scenes, null);
  assert.deepEqual(
    readScreensConfig({ screens: { enabled: true, capture: { generated_scenes: { file: GENERATED } } } })?.capture
      .generated_scenes,
    { file: GENERATED, setup: null }
  );
  for (const generated of [{ file: "e2e/*.ts" }, { file: "../outside.screens.ts" }, { file: GENERATED, setup: "e2e/*.ts" }, { setup: "x.ts" }]) {
    assert.throws(
      () => readScreensConfig({ screens: { enabled: true, capture: { generated_scenes: generated } } }),
      /screens\.capture\.generated_scenes/,
      JSON.stringify(generated)
    );
  }
});

await test("generates a scene for each page no other test captures, and says why it skips the rest", () => {
  const { plan } = planFor(workspace());
  assert.deepEqual(plan.scenes, [
    { key: "note-detail", route: "/notes/:noteId" },
    { key: "notes-list", route: "/notes" },
  ]);
  assert.deepEqual(plan.skipped, [
    { key: "notes-about", reason: "has_scene", files: ["e2e/about.screens.ts"] },
    { key: "notes-settings", reason: "not_captured" },
  ]);
  assert.equal(
    plan.content,
    [
      "// Generated by `tieline screens scenes` from the screen catalog: one scene for",
      "// each catalogued page no other test captures. Do not edit it. To capture a",
      "// page differently, write its scene in another file and regenerate; the page",
      "// then leaves this file.",
      'import { test } from "@playwright/test";',
      'import { tielinePageScene } from "tieline/playwright";',
      'import { prepare } from "./screens.setup";',
      "",
      'test("note-detail", { tag: "@screen:note-detail" }, async ({ page }) => {',
      '  await tielinePageScene(page, {"key":"note-detail","title":"A note, opened","route":"/notes/:noteId","applies_to":{"role":["member"]}}, prepare);',
      "});",
      "",
      'test("notes-list", { tag: "@screen:notes-list" }, async ({ page }) => {',
      '  await tielinePageScene(page, {"key":"notes-list","title":"Notes list","route":"/notes","applies_to":null}, prepare);',
      "});",
      "",
    ].join("\n")
  );
});

await test("without a setup module, skips routes with parameters and imports nothing extra", () => {
  const { plan } = planFor(workspace({ file: GENERATED }));
  assert.deepEqual(plan.scenes, [{ key: "notes-list", route: "/notes" }]);
  assert.ok(plan.skipped.some((skip) => skip.reason === "route_parameters" && skip.key === "note-detail"));
  assert.doesNotMatch(plan.content, /import \{ prepare \}/);
  assert.match(plan.content, /tielinePageScene\(page, \{[^}]*"applies_to":null\}\);/);
});

await test("imports the setup module by its path relative to the generated file", () => {
  for (const [file, setup, expected] of [
    ["e2e/generated/pages.screens.ts", "e2e/support/screens.setup.ts", "../support/screens.setup"],
    ["e2e/pages.screens.mjs", "e2e/screens.setup.mjs", "./screens.setup.mjs"],
  ] as const) {
    const { plan } = planFor(workspace({ file, setup }));
    assert.match(plan.content, new RegExp(`import \\{ prepare \\} from "${expected.replace(/[./]/g, "\\$&")}";`), file);
  }
});

await test("refuses a file the test scan would not read, or a setup module that is the same file", () => {
  const unscanned = screenSettingsForRepository(workspace({ file: "e2e/pages.ts" }).root)!;
  assert.match(generatedScenesFileProblem(unscanned)!, /'e2e\/pages\.ts' is not a file the test scan reads/);
  const same = screenSettingsForRepository(workspace({ file: GENERATED, setup: GENERATED }).root)!;
  assert.match(generatedScenesFileProblem(same)!, /must be different files/);
  const off = screenSettingsForRepository(workspace(null).root)!;
  assert.match(generatedScenesFileProblem(off)!, /not configured/);
});

